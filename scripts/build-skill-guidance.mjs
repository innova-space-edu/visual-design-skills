import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),"..");
const registry=JSON.parse(fs.readFileSync(path.join(root,"registry.json"),"utf8"));
const out={};

function section(text,heading){
  const re=new RegExp("^##\\s+"+heading+"\\s*$([\\s\\S]*?)(?=^##\\s+|$)","mi");
  const match=text.match(re);
  if(!match)return[];
  return match[1].split(/\\r?\\n/).map(line=>line.trim()).filter(line=>/^[-*]\\s+/.test(line)).map(line=>line.replace(/^[-*]\\s+/,"").trim()).filter(Boolean);
}
function description(text){
  const raw=text.match(/^description:\\s*(.+)$/m)?.[1]?.trim()||"";
  return raw.replace(/^[\\"\']|[\\"\']$/g,"").slice(0,320);
}
for(const item of registry.skills){
  const full=path.join(root,item.path);
  if(!fs.existsSync(full))continue;
  const text=fs.readFileSync(full,"utf8");
  let rules=section(text,"Specialist rules");
  if(!rules.length)rules=section(text,"Rules");
  if(!rules.length)rules=section(text,"Core principles");
  if(!rules.length)rules=section(text,"Requirements");
  out[item.name]={
    category:item.category,
    strategy:item.default_render_strategy,
    description:description(text),
    triggers:section(text,"Activate for").slice(0,5),
    rules:rules.slice(0,8),
    qa:section(text,"QA focus").slice(0,6)
  };
}
const header="// AUTO-GENERATED by scripts/build-skill-guidance.mjs.\\n";
const body="export const SKILL_GUIDANCE = Object.freeze("+JSON.stringify(out,null,2)+");\\n\\n";
const helpers=String.raw`const GENERATIVE_EXCLUDE = /\\b(?:deterministic|svg|maplibre|vega(?:-lite)?|geojson|cad|latex|typescript|javascript)\\b/i;

export function getSkillGuidance(skillNames = [], options = {}) {
  const maxSkills = options.maxSkills ?? 4;
  const maxRulesPerSkill = options.maxRulesPerSkill ?? 5;
  const maxQaPerSkill = options.maxQaPerSkill ?? 3;
  const mode = options.mode ?? "generative";
  const unique = [...new Set(skillNames)].slice(0, maxSkills);
  return unique.flatMap(name => {
    const item = SKILL_GUIDANCE[name];
    if (!item) return [];
    let rules = item.rules ?? [];
    if (mode === "generative") rules = rules.filter(rule => !GENERATIVE_EXCLUDE.test(rule));
    return [{ skill:name, description:item.description, rules:rules.slice(0,maxRulesPerSkill), qa:(item.qa ?? []).slice(0,maxQaPerSkill) }];
  });
}

export function compactSkillGuidance(skillNames = [], options = {}) {
  return getSkillGuidance(skillNames, options).map(item => {
    const rules = item.rules.length ? item.rules.join("; ") : item.description;
    return rules ? "[" + item.skill + "] " + rules : "";
  }).filter(Boolean).join("\\n");
}
`;
fs.writeFileSync(path.join(root,"packages/core/skill-guidance.js"),header+body+helpers);
console.log("Generated specialist guidance for "+Object.keys(out).length+" skills.");
